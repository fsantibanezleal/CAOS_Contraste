// Generates docs/contracts/api.openapi.json and src/lib/contract.gen.ts from the contract schema files (ADR-0080
// decision 5: the schema files are the single source of every contract; the TypeScript types are generated, never
// hand-written). Adapted from CAOS_PRODUCT_TEMPLATE v0.04.000 frontend/scripts/gen-contract-types.mjs.
//
// The OpenAPI 3.1 document is built in memory from docs/contracts/api.paths.json (the paths and the error bodies,
// by hand) plus ONE COMPONENT PER SCHEMA FILE found under docs/contracts/schemas/**/*.schema.json, named
// `<folder>-<name>` (`common-case-index`, `c04-variant-agency`). No file list exists anywhere: a case folder added by a
// later unit is picked up by the walk. Each file keeps its shared definitions in `$defs`; openapi-typescript would
// render `$defs` as a property of every document type, so the files are inlined here: every `$defs` entry becomes a
// component of its own name (one name, one definition: a name defined twice must be identical or the run fails) and
// every `$ref` between files becomes a reference to the component of the target file.
//
// `--check` regenerates both outputs in memory and exits 1 naming each committed file that differs, so a schema
// change without a regeneration stops `npm run check:contracts` (no CI job of its own, ADR-0074).
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, posix, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const here = dirname(fileURLToPath(import.meta.url));
const contracts = join(here, '..', '..', 'docs', 'contracts');
const schemasDir = join(contracts, 'schemas');
const openapiPath = join(contracts, 'api.openapi.json');
const genPath = join(here, '..', 'src', 'lib', 'contract.gen.ts');
const HEADER = '// GENERATED by frontend/scripts/gen-contract-types.mjs from docs/contracts/api.openapi.json. Do not edit.\n';

const readJSON = (path) => JSON.parse(readFileSync(path, 'utf8'));
const lf = (text) => text.replace(/\r\n/g, '\n');

/** Every `*.schema.json` under docs/contracts/schemas, as posix paths relative to it, sorted. */
function schemaFiles(dir = schemasDir) {
  const out = [];
  for (const name of readdirSync(dir).sort()) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) out.push(...schemaFiles(full));
    else if (name.endsWith('.schema.json')) out.push(relative(schemasDir, full).split(sep).join('/'));
  }
  return out.sort();
}

/** `c04/variant-agency.schema.json` -> `c04-variant-agency`. */
const componentName = (file) => file.replace(/\.schema\.json$/, '').replace(/\//g, '-');

/** A copy of `node` with every `$ref` pointed at a component: `#/$defs/<n>` -> `<n>`, `<file>` -> the file's
 * component, `<file>#/$defs/<n>` -> `<n>`. `file` is the posix path of the schema file the node came from. */
function relink(node, file) {
  if (Array.isArray(node)) return node.map((x) => relink(x, file));
  if (node === null || typeof node !== 'object') return node;
  const out = {};
  for (const [key, value] of Object.entries(node)) {
    if (key === '$ref' && typeof value === 'string') {
      const [target, fragment] = value.split('#');
      if (fragment && fragment.startsWith('/$defs/')) out[key] = `#/components/schemas/${fragment.slice('/$defs/'.length)}`;
      else if (!target) throw new Error(`${file}: unsupported local reference ${value}`);
      else out[key] = `#/components/schemas/${componentName(posix.normalize(posix.join(posix.dirname(file), target)))}`;
    } else out[key] = relink(value, file);
  }
  return out;
}

/** The OpenAPI document: api.paths.json plus the components of every schema file (inlined, `$defs` hoisted). */
export function buildDocument() {
  const doc = readJSON(join(contracts, 'api.paths.json'));
  const schemas = doc.components.schemas;
  const files = schemaFiles();
  const hoisted = {};
  const fileComponents = {};
  for (const file of files) {
    const { $defs = {}, $schema: _dialect, $id: _id, ...body } = readJSON(join(schemasDir, file));
    for (const [defName, def] of Object.entries($defs)) {
      const linked = relink(def, file);
      if (defName in hoisted && JSON.stringify(hoisted[defName]) !== JSON.stringify(linked)) {
        throw new Error(`$defs ${defName} of ${file} differs from the same name in another schema file: one name, one definition`);
      }
      hoisted[defName] = linked;
    }
    fileComponents[componentName(file)] = relink(body, file);
  }
  for (const name of [...Object.keys(fileComponents), ...Object.keys(hoisted)]) {
    if (name in schemas) throw new Error(`component ${name} collides with a hand-written component of api.paths.json`);
  }
  for (const name of Object.keys(hoisted)) {
    if (name in fileComponents) throw new Error(`$defs ${name} collides with the component of a schema file`);
  }
  Object.assign(schemas, fileComponents, hoisted);
  // the artifact endpoint serves any variant or models artifact: discovered, never listed
  const artifacts = Object.keys(fileComponents)
    .filter((n) => !n.startsWith('common-') && /-(variant|models)(-|$)/.test(n))
    .map((n) => ({ $ref: `#/components/schemas/${n}` }));
  const discover = (node) => {
    if (Array.isArray(node)) return node.map(discover);
    if (node === null || typeof node !== 'object') return node;
    if (node['x-discover'] === 'case-artifacts') return { anyOf: artifacts };
    return Object.fromEntries(Object.entries(node).map(([k, v]) => [k, discover(v)]));
  };
  doc.paths = discover(doc.paths);
  doc.components.schemas = Object.fromEntries(Object.entries(doc.components.schemas).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
  return doc;
}

const doc = buildDocument();
const openapiText = `${JSON.stringify(doc, null, 2)}\n`;
const ast = await openapiTS(doc);
const body = lf(astToString(ast)).replace(/\s+$/, '');
const genText = `${HEADER}${body}\n`;

const targets = [
  [openapiPath, openapiText, 'docs/contracts/api.openapi.json'],
  [genPath, genText, 'frontend/src/lib/contract.gen.ts'],
];

if (process.argv.includes('--check')) {
  const stale = [];
  for (const [path, text, label] of targets) {
    let current = null;
    try {
      current = lf(readFileSync(path, 'utf8'));
    } catch {
      // an absent file is not current
    }
    if (current !== text) stale.push(label);
  }
  if (stale.length) {
    console.error(`contract outputs are not current: ${stale.join(', ')}. Run npm run gen:contracts`);
    process.exit(1);
  }
  console.log(`contract outputs: current (${Object.keys(doc.components.schemas).length} components)`);
} else {
  for (const [path, text, label] of targets) {
    writeFileSync(path, text, 'utf8');
    console.log(`contract outputs: wrote ${label}`);
  }
}
