_DIGITS = dict(zip("0123456789", ("Zero", "One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine")))


def safe(name: str) -> str:
    """A TeX control sequence holds letters only: every digit of a macro name is spelled out (``c14`` becomes ``cOneFour``)."""
    return "".join(_DIGITS.get(ch, ch) for ch in name)


def write_numbers() -> None:
    lines = ["% Generated by make_tables.py: one macro per number of the prose; the comment names its source (a JSON path under experiments/)."]
    for name, value, source in _NUM:
        lines.append(f"% {source}")
        lines.append(f"\\newcommand{{\\{safe(name)}}}{{{value}}}")
    (OUT / "numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


