def T(path, header, rows, **kw):
    """``figkit.table`` with an optional group row above the header and, for the wide tables, the tabular scaled to the text width."""
    groups, lead = kw.pop("groups", None), kw.pop("lead", 1)
    out = figkit.table(path, header, rows, **kw)
    text = out.read_text(encoding="utf-8")
    if groups:
        cells, rules, col = [f"\\multicolumn{{{lead}}}{{l}}{{}}"], [], lead + 1
        for label, n in groups:
            cells.append(f"\\multicolumn{{{n}}}{{c}}{{{label}}}")
            rules.append(f"\\cmidrule(lr){{{col}-{col + n - 1}}}")
            col += n
        text = text.replace("\\toprule\n", "\\toprule\n" + " & ".join(cells) + " \\\\\n" + "".join(rules) + "\n", 1)
    text = text.replace("\\small\n", "\\footnotesize\n", 1)
    if path.stem in FIT_WIDTH:
        text = text.replace("\\begin{tabular}", "\\resizebox{\\textwidth}{!}{%\n\\begin{tabular}", 1).replace("\\end{tabular}", "\\end{tabular}}", 1)
    out.write_text(text, encoding="utf-8", newline="\n")
    return out


