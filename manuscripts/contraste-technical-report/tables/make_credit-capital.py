def load() -> dict[str, Any]:
    """The seven documents of case C10 and the models document, keyed by variant id."""
    d = {lid: figkit.doc(f"C10/{lid}.json") for lid, _, _ in LOANS}
    d["models"] = figkit.doc("C10/models-c10.json")
    d["grid-22"] = figkit.doc("C10/grid-22.json")
    d["grid-40"] = figkit.doc("C10/grid-40.json")
    return d


def rung(doc: dict, rid: str) -> dict:
    return next(r for r in doc["outputs"]["rungs"] if r["id"] == rid)


def meas(doc: dict, rid: str, level: float) -> dict:
    return next(m for m in rung(doc, rid)["measures"] if abs(m["level"] - level) < 1e-12)


def test_rows(doc: dict, test_id: str) -> list[dict]:
    return [t for t in doc["tests"] if t["test_id"] == test_id]


def bt_row(doc: dict, level: float) -> dict:
    return next(r for r in doc["outputs"]["backtest"]["rows"] if abs(r["level"] - level) < 1e-12)


# ---------------------------------------------------------------- number formats


def f(x: float, d: int) -> str:
    return f"{x:.{d}f}"


def mil(x: float, d: int = 2) -> str:
    """Money in millions of USD."""
    return f"{x / 1e6:.{d}f}"


def pct(x: float, d: int = 2) -> str:
    """A share as a percentage, without the sign."""
    return f"{100.0 * x:.{d}f}"


def sci(x: float, d: int = 1) -> str:
    """A small number as ``\\ensuremath{m \\times 10^{e}}`` (usable in text, in math and as a table cell)."""
    if x == 0:
        return "\\ensuremath{0}"
    e = math.floor(math.log10(abs(x)))
    m = x / 10 ** e
    return f"\\ensuremath{{{m:.{d}f}\\times10^{{{e}}}}}"


def pval(p: float) -> str:
    if p >= 0.001:
        return f"{p:.3f}"
    if p >= 1e-4:
        return f"{p:.4f}"
    return sci(p, 1)


def thousands(n: int | float) -> str:
    return f"{int(round(n)):,}"


def mac(name: str, value: str, source: str) -> str:
    """Register a number of the prose as ``\\cc<name>`` and return the value."""
    if not re.fullmatch(r"[A-Za-z]+", name):
        raise ValueError(f"macro name {name!r} must hold letters only")
    MACROS["cc" + name] = (value, source)
    return value


def write_macros(path: pathlib.Path) -> None:
    lines = ["% Generated by tables/make_credit-capital.py from data/derived/C10: do not edit.",
             "% One macro per number the credit-capital section quotes."]
    for k, (v, _) in sorted(MACROS.items()):
        lines.append(f"\\newcommand{{\\{k}}}{{{v}}}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


