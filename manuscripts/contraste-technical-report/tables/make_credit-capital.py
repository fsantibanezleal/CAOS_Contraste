def tbl(name: str, header, rows, *, caption: str, label: str, align: str | None = None, digits: int = 3) -> None:
    figkit.table(OUT / f"credit-capital-{name}.tex", header, rows, caption=caption, label=label, align=align, digits=digits)


def P(w: float) -> str:
    """A left-aligned paragraph column of width ``w`` cm (text wraps inside the cell)."""
    return ">{\\raggedright\\arraybackslash}p{%scm}" % w


def R(w: float) -> str:
    """A right-aligned paragraph column of width ``w`` cm (a long header wraps, numbers stay right-aligned)."""
    return ">{\\raggedleft\\arraybackslash}p{%scm}" % w


def interval(est: float, lo: float, hi: float, d: int = 3) -> str:
    return f"${est:.{d}f}$ [${lo:.{d}f}$, ${hi:.{d}f}$]"


